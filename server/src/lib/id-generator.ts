/**
 * ID 生成端口。
 *
 * 干什么: 抽象"给我一个新 id",实现走 UUID v7。
 * 解决什么问题: 测试里可以注入一个自增的假实现,让断言里出现的是 'id-1' 而不是
 *   一串随机 UUID —— 失败信息可读得多。
 *
 * 为什么是 UUID v7 而不是 v4: v7 的高位是毫秒时间戳,所以字典序 ≈ 时间序。
 * 对 SQLite 这类 B-tree 索引,单调递增的主键意味着插入总是发生在树的右端,
 * 不会像 v4 那样把页分裂散布到整棵树上。同时"按 id 排序"天然就是"按创建时间排序"。
 */
export interface IdGenerator {
  next(): string;
}
